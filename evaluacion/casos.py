def iban(pais: str, bban: str) -> str:
    """Construye un IBAN válido calculando los dígitos de control."""
    reordenado = bban + pais + "00"
    numero = int("".join(str(int(c, 36)) for c in reordenado))
    return f"{pais}{98 - numero % 97:02d}{bban}"


